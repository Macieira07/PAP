  <h2>Política de Privacidade</h2>

  <p>A Quinta Flores, com o email de contacto <a href="mailto:quintaflores2019@gmail.com">quintaflores2019@gmail.com</a>, compromete-se a proteger a privacidade dos seus visitantes e clientes. Esta política explica como recolhemos, usamos, armazenamos e protegemos os seus dados pessoais.</p>

  <h3>1. Dados que recolhemos</h3>
  <ul>
    <li>Nome</li>
    <li>Endereço de email</li>
    <li>Contacto telefónico</li>
    <li>NIF</li>
    <li>Palavra-passe (encriptada)</li>
    <li>Informações de reserva (datas, número de hóspedes, preferências, etc.)</li>
  </ul>

  <h3>2. Finalidade do tratamento</h3>
  <p>Utilizamos os dados para:</p>
  <ul>
    <li>Gerir reservas</li>
    <li>Entrar em contacto com o cliente</li>
    <li>Cumprir obrigações legais (ex: faturação)</li>
    <li>Melhorar a experiência no site</li>
  </ul>

  <h3>3. Base legal</h3>
  <p>Tratamos os dados com base no consentimento do utilizador, na execução de um contrato (reserva), e no cumprimento de obrigações legais.</p>

  <h3>4. Partilha de dados</h3>
  <p>Não partilhamos os dados com terceiros, exceto quando necessário por obrigação legal ou para funcionamento de serviços como o Google Maps.</p>

  <h3>5. Tempo de retenção</h3>
  <p>Os dados são guardados durante o tempo necessário à finalidade para a qual foram recolhidos e pelo período exigido por lei (ex: 10 anos para fins fiscais).</p>

  <h3>6. Direitos dos utilizadores</h3>
  <p>Tem o direito de:</p>
  <ul>
    <li>Aceder aos seus dados</li>
    <li>Corrigir ou apagar dados</li>
    <li>Retirar o consentimento</li>
    <li>Solicitar a portabilidade dos dados</li>
    <li>Apresentar reclamação à CNPD</li>
  </ul>

  <h3>7. Segurança</h3>
  <p>Adotamos medidas técnicas e organizativas adequadas para proteger os seus dados, incluindo encriptação de palavras-passe.</p>

  <h3>8. Contacto</h3>
  <p>Para qualquer questão relacionada com os seus dados, contacte-nos: <a href="mailto:quintaflores2019@gmail.com">quintaflores2019@gmail.com</a></p>

  <h3>9. Atualizações</h3>
  <p>Última atualização: 16 de junho de 2025. Esta política pode ser atualizada sem aviso prévio.</p>
